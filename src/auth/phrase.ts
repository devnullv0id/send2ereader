export const PHRASE_WORDS = 6

export function phraseWordCount(): number {
  return WORDS.length
}

export function makeRecoveryPhrase(): string {
  const picked: string[] = []
  for (let i = 0; i < PHRASE_WORDS; i++) picked.push(WORDS[randomInt(WORDS.length)]!)
  return picked.join('-')
}
